import type { AppNotification, Decision, TimelineEvent, TimelineType } from '../types';

const ago = (days: number, hours = 0): string =>
  new Date(Date.now() - days * 86400000 - hours * 3600000).toISOString();

const ahead = (days: number): string =>
  new Date(Date.now() + days * 86400000).toISOString();

const ev = (
  type: TimelineType,
  label: string,
  date: string,
  detail?: string,
): TimelineEvent => ({
  id: `t-${type}-${label.length}-${Math.floor(Math.random() * 1e6)}`,
  type,
  label,
  date,
  detail,
});

